// 从 SDK 类型生成两端共用的结构契约；运行时不携带生成器或 Ajv。
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const require = createRequire(`${root}frontend/package.json`)
const { createGenerator } = require('ts-json-schema-generator')
const Ajv = require('ajv')
const standalone = require('ajv/dist/standalone').default
const { build } = require('esbuild')
const names = ['TeachingFrame', 'SimPackageDescriptor', 'RuntimeFrame']
const schema = createGenerator({
  path: `${root}frontend/packages/sim-sdk/src/types.ts`,
  tsconfig: `${root}frontend/packages/sim-sdk/tsconfig.json`,
  type: names, additionalProperties: true, functions: 'fail',
}).createSchema(names)
schema.$id = 'urn:chaimir:sim:runtime'
const ajv = new Ajv({ code: { source: true, esm: true }, strict: true, allowUnionTypes: true })
ajv.addSchema(schema)
const validators = Object.fromEntries(names.map(name => [`is${name}`, `${schema.$id}#/definitions/${name}`]))
const { outputFiles } = await build({
  stdin: { contents: standalone(ajv, validators), resolveDir: `${root}frontend`, sourcefile: 'sim-protocol.js' },
  bundle: true, write: false, format: 'esm', platform: 'neutral', minify: true,
})
const outputs = new Map([
  ['backend/internal/modules/sim/runtime_protocol.schema.json', `${JSON.stringify(schema, null, 2)}\n`],
  ['frontend/packages/sim-sdk/src/protocol.generated.ts', `// @ts-nocheck\n// Generated by scripts/codegen/sim-runtime-protocol.mjs; do not edit.\n${outputFiles[0].text}`],
])
for (const [path, value] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(root + path, 'utf8') !== value) throw new Error(`${path} 已偏离 SDK 类型，请重新生成`)
  } else writeFileSync(root + path, value)
}
console.log(`仿真运行契约${process.argv.includes('--check') ? '一致' : '已生成'}：${names.join(', ')}`)
